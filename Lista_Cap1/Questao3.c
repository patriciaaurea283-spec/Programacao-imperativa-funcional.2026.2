#include <stdio.h> /* Biblioteca para utilizar a função printf() */
#include <stdlib.h> /* Biblioteca para utilizar a função system("pause") */

int main () { /* Função principal obrigatória para o programa funcionar */

    // Exibe uma mensagem na tela utilizando a função printf()
    printf("Este programa demonstra o uso de comentarios em C.\n");

    // Pausa o programa até que uma tecla seja pressionada
    system("pause");

    return 0; /* Retorna 0 indicando que o programa foi executado corretamente */

} /* Fim do corpo da função main */